"""Offline Natural Earth -> small pixel-centre mask + sample grid (stdlib only).
Run from any directory; network used only with --download. Firmware never loads GeoJSON.
"""
import hashlib
import json
from pathlib import Path
import sys
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
REV = 'ca96624a56bd078437bca8184e78163e5039ad19'
URL = f'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/{REV}/geojson/ne_50m_admin_0_countries.geojson'
ASSET = ROOT / 'assets/map/thailand.geojson'
if '--download' in sys.argv:
    raw = urllib.request.urlopen(URL, timeout=60).read()
    data = json.loads(raw)
    feature = next(f for f in data['features'] if f['properties']['ADM0_A3'] == 'THA')
    ASSET.write_text(json.dumps(feature, separators=(',', ':')) + '\n', encoding='utf-8')
    (ROOT / 'assets/map/source.json').write_text(json.dumps(dict(url=URL, upstream_sha256=hashlib.sha256(raw).hexdigest(), license='Public domain', terms='https://www.naturalearthdata.com/about/terms-of-use/'), indent=2)+'\n')
feature = json.loads(ASSET.read_text())
polygons = feature['geometry']['coordinates']
assert feature['geometry']['type'] == 'MultiPolygon'

def ring_contains(ring, x, y):
    inside = False
    for a, b in zip(ring, ring[1:] + ring[:1]):
        if (a[1] > y) != (b[1] > y) and x < (b[0]-a[0])*(y-a[1])/(b[1]-a[1])+a[0]:
            inside = not inside
    return inside

def contains(x, y):
    return any(ring_contains(p[0], x, y) and not any(ring_contains(h, x, y) for h in p[1:]) for p in polygons)

# Equirectangular at ~15N; 148x230 covers Thailand, including southern tip.
W, H = 148, 230
WEST, EAST, SOUTH, NORTH = 97.0, 106.0, 5.5, 20.7
mask = bytearray((W*H+7)//8)
for y in range(H):
    for x in range(W):
        if contains(WEST+(x+.5)*(EAST-WEST)/W, NORTH-(y+.5)*(NORTH-SOUTH)/H):
            i = y*W+x
            mask[i//8] |= 1 << (i%8)
# Regular interior locations plus southern peninsula locations. No invented boundary.
samples = [(lat, lon) for lat in [7., 8.5, 10., 11.5, 13., 14.5, 16., 17.5, 19., 20.] for lon in [97.5, 99., 100.5, 102., 103.5, 105.] if contains(lon, lat)]
for lat, lon in [(6.3,101.3),(8.1,98.5),(9.5,99.1),(10.5,99.2),(12.,99.8)]:
    if contains(lon,lat):
        samples.append((lat,lon))
lines = ['#pragma once', '#include <stdint.h>', '// Generated by tools/generate_thailand.py; Natural Earth public domain.', 'namespace thailand {', f'constexpr int WIDTH={W}, HEIGHT={H};', f'constexpr float WEST={WEST}f, EAST={EAST}f, SOUTH={SOUTH}f, NORTH={NORTH}f;', 'struct Location { float lat, lon; };', 'constexpr Location LOCATIONS[] = {']
lines += [f'    {{{lat:.3f}f, {lon:.3f}f}},' for lat,lon in samples]
lines += ['};', 'constexpr unsigned COUNT = sizeof(LOCATIONS)/sizeof(LOCATIONS[0]);', 'constexpr uint8_t MASK[] = {']
lines += ['    '+','.join(str(b) for b in mask[i:i+28])+',' for i in range(0,len(mask),28)]
lines += ['};', 'inline bool contains_pixel(int x, int y) {', '    if (x<0 || y<0 || x>=WIDTH || y>=HEIGHT) return false;', '    unsigned i=y*WIDTH+x; return (MASK[i/8] & (1u << (i%8))) != 0;', '}', '}']
(ROOT/'src/thailand_mask.h').write_text('\n'.join(lines)+'\n')
print(f'Generated {len(mask)} mask bytes, {len(samples)} locations; islands below pixel size omitted.')
