"""Generate embedded ASCII GFX fonts from Nunito (OFL); run with Python + Pillow.

Firmware builds use the committed header and do not need Python or Pillow.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/fonts/Nunito.ttf"
OUTPUT = ROOT / "src/ui_fonts.h"


def generate_font(size):
    font = ImageFont.truetype(str(SOURCE), size)
    font.set_variation_by_axes([700])
    bitmap = []
    glyphs = []
    for code in range(32, 127):
        char = chr(code)
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right - left, bottom - top
        offset = len(bitmap)
        if char == " ":
            width = height = 0
        if width and height:
            image = Image.new("L", (width, height))
            ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor="ls")
            bits = [1 if p >= 96 else 0 for p in image.getdata()]
            for start in range(0, len(bits), 8):
                byte = 0
                for bit in bits[start:start + 8]:
                    byte = (byte << 1) | bit
                byte <<= max(0, start + 8 - len(bits))
                bitmap.append(byte)
        glyphs.append((offset, width, height, round(font.getlength(char)), left, top))
    name = f"nunito_{size}"
    lines = [f"const uint8_t {name}_bitmap[] PROGMEM = {{"]
    for start in range(0, len(bitmap), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in bitmap[start:start + 16]) + ",")
    lines.append("};")
    lines.append(f"const GFXglyph {name}_glyphs[] PROGMEM = {{")
    for glyph in glyphs:
        lines.append("    {" + ", ".join(str(n) for n in glyph) + "},")
    lines.extend(["};", f"const GFXfont {name} PROGMEM = {{",
                  f"    (uint8_t *){name}_bitmap, (GFXglyph *){name}_glyphs, 32, 126, {sum(font.getmetrics())}",
                  "};", ""])
    advance = lambda text: sum(round(font.getlength(c)) for c in text)
    print(f"Nunito Bold {size}px: {len(bitmap)} bitmap bytes, instruction {advance('Plz Click on corner')}px")
    if size == 26:
        assert advance("Plz Click on corner") <= 296
    return "\n".join(lines)


if __name__ == "__main__":
    header = "#pragma once\n\n// Generated by tools/generate_ui_fonts.py.\n// Nunito Bold ASCII subset, Copyright 2014 The Nunito Project Authors.\n// SIL Open Font License 1.1: assets/fonts/OFL.txt\n// GFX types are provided by TFT_eSPI with LOAD_GFXFF enabled.\n\n"
    OUTPUT.write_text(header + generate_font(18) + generate_font(26), encoding="utf-8")
